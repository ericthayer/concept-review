/**
 * Verifies WCAG contrast for every token pair the design uses and writes
 * docs/contrast.md. Fails the build on any pair below its threshold.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './load-content.ts';

type Theme = 'light' | 'dark';

const css = readFileSync(join(ROOT, 'src/styles/tokens.css'), 'utf8');

function tokens(block: string): Map<string, string> {
  const map = new Map<string, string>();
  for (const m of block.matchAll(/(--[a-z0-9-]+):\s*(#[0-9a-f]{6})\s*;/gi)) {
    const [, name, value] = m;
    if (name && value) map.set(name, value.toLowerCase());
  }
  return map;
}

const rootBlock = css.slice(css.indexOf(':root {'), css.indexOf('}', css.indexOf(':root {')));
const darkBlock = css.slice(css.indexOf(":root[data-theme='dark'] {"), css.indexOf('}', css.indexOf(":root[data-theme='dark'] {")));
const light = tokens(rootBlock);
const dark = new Map([...light, ...tokens(darkBlock)]);

function luminance(hex: string): number {
  const n = parseInt(hex.slice(1), 16);
  const ch = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((c) => {
    const s = c / 255;
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * (ch[0] ?? 0) + 0.7152 * (ch[1] ?? 0) + 0.0722 * (ch[2] ?? 0);
}

export function ratio(a: string, b: string): number {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x) as [number, number];
  return (hi + 0.05) / (lo + 0.05);
}

interface Pair {
  readonly fg: string;
  readonly bg: string;
  readonly use: string;
  /** 4.5 text, 3 large text / non-text */
  readonly min: 4.5 | 3;
  readonly themes: readonly Theme[];
}

const PAIRS: readonly Pair[] = [
  { fg: '--ink-text', bg: '--paper', use: 'Panel copy, captions, headings on paper', min: 4.5, themes: ['light', 'dark'] },
  { fg: '--ink-text', bg: '--paper-2', use: 'Info strip, balloons, controls', min: 4.5, themes: ['light', 'dark'] },
  { fg: '--paper-text', bg: '--ink-0', use: 'Knockout labels, masthead, footer, page ground', min: 4.5, themes: ['light', 'dark'] },
  { fg: '--ink-0', bg: '--ticket', use: 'Buy Tickets and CTA panels', min: 4.5, themes: ['light', 'dark'] },
  { fg: '--paper-text', bg: '--pop-red', use: 'TODO tags, notice labels', min: 4.5, themes: ['light', 'dark'] },
  { fg: '--ink-text', bg: '--doc-sepia', use: 'Text over documentary sepia', min: 4.5, themes: ['light'] },
  { fg: '--ticket', bg: '--ink-0', use: 'Focus ring on black (non-text)', min: 3, themes: ['light', 'dark'] },
  { fg: '--ink-0', bg: '--paper', use: 'Focus ring inner ring on paper (non-text)', min: 3, themes: ['light'] },
  { fg: '--ink-0', bg: '--ticket', use: 'Focus ring inner ring on gold (non-text)', min: 3, themes: ['light', 'dark'] },
  { fg: '--notice-edge', bg: '--paper', use: 'Notice panel edge, TODO outline (non-text)', min: 3, themes: ['light', 'dark'] },
  { fg: '--pencil', bg: '--paper', use: 'Under-construction pencil lines (non-text)', min: 3, themes: ['light'] },
  { fg: '--ink-0', bg: '--pop-green-art', use: 'Linework over green fills (non-text)', min: 3, themes: ['light'] },
  { fg: '--ink-0', bg: '--pop-blue', use: 'Linework over blue fills (non-text)', min: 3, themes: ['light'] },
  { fg: '--ink-0', bg: '--pop-magenta', use: 'Linework over magenta fills (non-text)', min: 3, themes: ['light'] },
  { fg: '--ink-0', bg: '--pop-orange', use: 'Linework over orange fills (non-text)', min: 3, themes: ['light'] },
];

const rows: string[] = [];
const failures: string[] = [];
for (const p of PAIRS) {
  for (const theme of p.themes) {
    const t = theme === 'light' ? light : dark;
    const fg = t.get(p.fg);
    const bg = t.get(p.bg);
    if (!fg || !bg) {
      failures.push(`${p.fg} on ${p.bg} (${theme}): token missing`);
      continue;
    }
    const r = ratio(fg, bg);
    const pass = r >= p.min;
    rows.push(`| ${p.use} | \`${p.fg}\` ${fg} | \`${p.bg}\` ${bg} | ${theme} | ${r.toFixed(2)}:1 | ${p.min}:1 | ${pass ? 'Pass' : '**Fail**'} |`);
    if (!pass) failures.push(`${p.fg} on ${p.bg} (${theme}) = ${r.toFixed(2)} < ${p.min}`);
  }
}

const doc = `# Contrast

Generated by \`npm run check:contrast\` from \`src/styles/tokens.css\`. Do not edit by hand.

Pop colors are fills, never text: any caption on a pop fill sits in a black knockout box,
so text contrast never depends on the fill. In dark mode, art linework switches to paper
and the knockout boxes stay black with paper text.

The focus indicator is a 3px \`--ticket\` outline plus a 2px \`--ink-0\` ring, so at least one
of the two rings clears 3:1 against paper, black, gold and every pop fill.

| Use | Foreground | Background | Theme | Ratio | Minimum | Result |
|---|---|---|---|---|---|---|
${rows.join('\n')}
`;
writeFileSync(join(ROOT, 'docs/contrast.md'), doc);
if (failures.length) {
  console.error(`Contrast failures:\n${failures.join('\n')}`);
  process.exit(1);
}
console.log(`Contrast: ${rows.length} pairs pass. Wrote docs/contrast.md`);
