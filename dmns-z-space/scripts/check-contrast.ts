/**
 * Contrast audit: resolves tokens.css for both themes and checks every token pair the
 * stylesheets actually use. Writes docs/contrast.md; exits non-zero on any failure.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { type Rgb, contrastRatio, mixOklch, parseHex, toHex } from '../src/lib/color.js';
import { ROOT } from './build.js';

type Theme = 'After Hours (dark)' | 'Daylight (light)';
type Tokens = Map<string, string>;

function declarations(block: string): Tokens {
  const out: Tokens = new Map();
  for (const m of block.matchAll(/--([\w-]+):\s*([^;]+);/g)) if (m[1] && m[2]) out.set(m[1], m[2].trim());
  return out;
}

function blockAfter(css: string, selector: string): string {
  const start = css.indexOf(selector);
  if (start === -1) throw new Error(`tokens.css: missing ${selector}`);
  const open = css.indexOf('{', start);
  let depth = 0;
  for (let i = open; i < css.length; i++) {
    if (css[i] === '{') depth++;
    if (css[i] === '}' && --depth === 0) return css.slice(open + 1, i);
  }
  throw new Error(`tokens.css: unterminated ${selector}`);
}

function resolver(tokens: Tokens): (name: string) => Rgb {
  const named: Readonly<Record<string, string>> = { white: '#ffffff', black: '#000000' };
  const resolveValue = (value: string, seen: Set<string>): Rgb => {
    const v = value.trim();
    if (v.startsWith('#')) return parseHex(v);
    if (named[v]) return parseHex(named[v]);
    const ref = /^var\(--([\w-]+)\)$/.exec(v);
    if (ref?.[1]) return resolveName(ref[1], seen);
    const mix = /^color-mix\(in oklch,\s*(.+?),\s*([\w#()-]+(?:\([^)]*\))?)\s+(\d+(?:\.\d+)?)%\)$/.exec(v);
    if (mix?.[1] && mix[2] && mix[3]) return mixOklch(resolveValue(mix[1], seen), resolveValue(mix[2], seen), Number(mix[3]) / 100);
    throw new Error(`Cannot resolve color value "${v}"`);
  };
  const resolveName = (name: string, seen = new Set<string>()): Rgb => {
    if (seen.has(name)) throw new Error(`Cycle at --${name}`);
    const value = tokens.get(name);
    if (!value) throw new Error(`Unknown token --${name}`);
    return resolveValue(value, new Set([...seen, name]));
  };
  return (name) => resolveName(name);
}

interface Pair {
  readonly fg: string;
  readonly bg: string;
  readonly use: string;
  /** 4.5 body text, 3 for large text and non-text UI (1.4.11, 2.4.11). */
  readonly min: 4.5 | 3;
}

const SURFACES = ['surface-0', 'surface-1', 'surface-2'] as const;
const TEXT_WINGS = ['wing-space', 'wing-life', 'wing-deep-time', 'wing-wildlife', 'wing-special', 'wing-theaters', 'wing-science', 'wing-plaza'] as const;

const PAIRS: readonly Pair[] = [
  ...SURFACES.map((bg): Pair => ({ fg: 'ink', bg, use: 'Primary text', min: 4.5 })),
  ...SURFACES.map((bg): Pair => ({ fg: 'ink-muted', bg, use: 'Secondary text', min: 4.5 })),
  ...TEXT_WINGS.flatMap((fg) => (['surface-0', 'surface-1'] as const).map((bg): Pair => ({ fg, bg, use: 'Wing label text (Jost caps)', min: 4.5 }))),
  { fg: 'on-ticket', bg: 'accent-ticket', use: 'Buy Tickets label', min: 4.5 },
  { fg: 'surface-0', bg: 'ink', use: 'Notice badge', min: 4.5 },
  // Focus rings sit 2px off the element, so both adjacent pixels are page surface.
  ...SURFACES.map((bg): Pair => ({ fg: 'signal', bg, use: 'Focus ring, current-room dot, TODO outline', min: 3 })),
  { fg: 'signal', bg: 'surface-1', use: 'Current room link text in the minimap', min: 4.5 },
  { fg: 'signal', bg: 'surface-2', use: 'Active floor numeral (bold caps)', min: 4.5 },
];

function audit(theme: Theme, tokens: Tokens): { rows: string[]; failures: string[] } {
  const color = resolver(tokens);
  const rows: string[] = [];
  const failures: string[] = [];
  for (const pair of PAIRS) {
    const fg = color(pair.fg);
    const bg = color(pair.bg);
    const ratio = contrastRatio(fg, bg);
    const pass = ratio >= pair.min;
    rows.push(`| ${theme} | \`--${pair.fg}\` ${toHex(fg)} | \`--${pair.bg}\` ${toHex(bg)} | ${ratio.toFixed(2)}:1 | ${pair.min}:1 | ${pass ? 'Pass' : '**Fail**'} | ${pair.use} |`);
    if (!pass) failures.push(`${theme}: --${pair.fg} on --${pair.bg} is ${ratio.toFixed(2)}:1 (needs ${pair.min}:1)`);
  }
  return { rows, failures };
}

const css = readFileSync(join(ROOT, 'src', 'styles', 'tokens.css'), 'utf8');
const dark = declarations(blockAfter(css, ':root {'));
const light = new Map([...dark, ...declarations(blockAfter(css, ":root[data-theme='light']"))]);
const results = [audit('After Hours (dark)', dark), audit('Daylight (light)', light)];

const doc = `# Contrast audit

Generated by \`npm run check:contrast\` (\`scripts/check-contrast.ts\`) from \`src/styles/tokens.css\`.
Do not edit by hand. \`color-mix(in oklch, …)\` tokens are resolved with the same math the browser uses.

Thresholds: 4.5:1 for text (1.4.3), 3:1 for focus indicators and non-text UI (1.4.11, 2.4.11).
DMNS purple, red and royal blue are never used as text on dark: purple and royal blue appear only
lightened (\`--wing-special\`, \`--wing-theaters\`), red is unused.

| Theme | Foreground | Background | Ratio | Minimum | Result | Used for |
|---|---|---|---|---|---|---|
${results.flatMap((r) => r.rows).join('\n')}
`;
writeFileSync(join(ROOT, 'docs', 'contrast.md'), doc);

const failures = results.flatMap((r) => r.failures);
if (failures.length) {
  console.error(`Contrast failures:\n  ${failures.join('\n  ')}`);
  process.exit(1);
}
console.log(`Contrast: ${PAIRS.length * 2} pairs pass. Wrote docs/contrast.md`);
